class ShiftItem {
  final String role;
  final String title;
  final DateTime date;
  final String time;
  final String location;
  final String ratePerHour;

  ShiftItem({
    required this.role,
    required this.title,
    required this.date,
    required this.time,
    required this.location,
    required this.ratePerHour,
  });
}